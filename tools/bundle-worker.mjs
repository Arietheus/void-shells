/* Produces server/worker-bundled.js: the whole Worker as one file, ready to
   paste into Cloudflare's web editor.

   The dashboard's editor only really wants one file, so the import of
   ./limits.js is resolved here instead. Everything else is copied verbatim,
   which matters — worker-bundled.js and src/index.js must not be allowed to
   drift into two different servers. Regenerate after any change to either
   src/index.js or the generated limits:

     node tools/gen-limits.mjs      (only if the game's tables changed)
     node tools/bundle-worker.mjs

   Run with: node tools/bundle-worker.mjs */
import fs from "fs";

const here = (p) => new URL(p, import.meta.url);
const src = fs.readFileSync(here("../server/src/index.js"), "utf8");
const limits = fs.readFileSync(here("../server/src/limits.js"), "utf8");

// strip the export keywords so the two files can share one scope
const inlined = limits
  .replace(/^export const /gm, "const ")
  .trim();

const IMPORT = 'import { LIMITS, MAX_WAVE } from "./limits.js";';
if (!src.includes(IMPORT)) {
  console.error("the import line moved -- update tools/bundle-worker.mjs");
  process.exit(1);
}

const banner = `/* GENERATED by tools/bundle-worker.mjs -- do not edit by hand.

   This is server/src/index.js and server/src/limits.js welded into one file,
   so it can be pasted straight into Cloudflare's dashboard editor. Edit the
   originals and rerun the bundler; edits made here are lost the next time
   anybody does.

   Paste target: Compute (Workers) -> void-shells-board -> Edit code.
   Generated ${new Date().toISOString().slice(0, 10)}. */

`;

const out = banner + src.replace(IMPORT, inlined);

fs.writeFileSync(here("../server/worker-bundled.js"), out);
console.log("wrote server/worker-bundled.js (" +
  (out.length / 1024).toFixed(1) + " KB, " + out.split("\n").length + " lines)");
